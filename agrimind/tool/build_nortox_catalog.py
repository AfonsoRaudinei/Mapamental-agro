#!/usr/bin/env python3
"""Gera catalog_nortox_records.dart a partir de tool/nortox_protecao_2025.md"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MD = ROOT / "nortox_protecao_2025.md"
OUT = ROOT.parent / "lib/features/catalog/data/datasources/catalog_nortox_records.dart"

SECTION_CAT = {
    "Inseticidas": "Inseticida",
    "Fungicidas": "Fungicida",
    "Inseticida + Fungicida": "Inseticida",
    "Herbicidas": "Herbicida",
    "Adjuvantes": "Adjuvante TA",
    "Reguladores de Crescimento": "Bioestimulante",
    "Protetor de Sementes": "Bioestimulante",
}


def unidade(conc: str) -> str:
    c = conc.lower()
    if "/kg" in c:
        return "kg/ha"
    return "L/ha"


def parse_md(text: str):
    current_cat = None
    records = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("## "):
            title = line[3:].strip()
            current_cat = SECTION_CAT.get(title)
            continue
        if not line.startswith("|") or line.startswith("|---"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 5:
            continue
        parts = [p for p in parts if p != ""]
        if parts[0].lower() in ("produto", "produto "):
            continue
        nome, ia, conc = parts[0], parts[1], parts[2]
        extra = parts[3] if len(parts) > 3 else ""
        if current_cat is None:
            continue
        if current_cat == "Adjuvante TA":
            culturas = ""
        elif current_cat == "Bioestimulante" and "cana" in extra.lower():
            culturas = "Cana-de-açúcar"
        elif current_cat == "Bioestimulante" and "sorgo" in extra.lower():
            culturas = "Sorgo"
        else:
            culturas = extra
        records.append(
            {
                "nome": nome.replace("'", "\\'"),
                "ia": ia.replace("'", "\\'"),
                "conc": conc.replace("'", "\\'"),
                "cat": current_cat,
                "unid": unidade(conc),
                "culturas": culturas.replace("'", "\\'"),
            }
        )
    return records


def main():
    text = MD.read_text(encoding="utf-8")
    records = parse_md(text)
    lines = [
        "// GENERATED by tool/build_nortox_catalog.py — não editar manualmente.",
        "",
        "const List<Map<String, String>> catalogNortoxRecords = [",
    ]
    for r in records:
        lines.append("  {")
        for k in ("nome", "ia", "conc", "cat", "unid", "culturas"):
            lines.append(f"    '{k}': r'{r[k]}',")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(records)} products to {OUT}")


if __name__ == "__main__":
    main()
