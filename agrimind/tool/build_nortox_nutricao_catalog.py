#!/usr/bin/env python3
"""Gera catalog_nortox_nutricao_records.dart a partir de tool/nortox_nutricao_2025.md"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MD = ROOT / "nortox_nutricao_2025.md"
OUT = ROOT.parent / "lib/features/catalog/data/datasources/catalog_nortox_nutricao_records.dart"

CULTURA_FUNCAO = {
    "multiculturas": "Soja, Milho, Café, Algodão, Trigo, Cana-de-açúcar",
    "leguminosas": "Soja, Feijão",
    "algodão": "Algodão",
    "gramíneas": "Milho, Sorgo, Trigo, Triticale",
    "gramineas": "Milho, Sorgo, Trigo, Triticale",
}


def unidade(garantias: str, dose: str = "") -> str:
    blob = f"{garantias} {dose}".lower()
    if "d 1" in blob or "kg/l" in blob or " g/l" in blob:
        return "L/ha"
    if "kg/ha" in blob:
        return "kg/ha"
    if "ml" in blob and "100 l" in blob:
        return "mL/ha"
    if "sacos 25 kg" in blob or "pó" in blob or "granulação" in blob:
        return "kg/ha"
    return "L/ha"


def culturas_from_funcao(funcao: str) -> str:
    f = funcao.lower()
    for key, culturas in CULTURA_FUNCAO.items():
        if key in f:
            return culturas
    if "cana" in f:
        return "Cana-de-açúcar"
    if "café" in f or "citros" in f:
        return "Café, Citros"
    return ""


def parse_md(text: str):
    cat = None
    section = ""
    records = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("# CAT:"):
            cat = line.replace("# CAT:", "").strip()
            continue
        if line.startswith("## "):
            section = line[3:].strip()
            if "bioestimulante" in section.lower():
                cat = cat or "Bioestimulante"
            if "condicionador" in section.lower() or "antideriva" in section.lower():
                cat = "Adjuvante TA"
            if "inoculante" in section.lower():
                cat = "Bioestimulante"
            continue
        if not line.startswith("|") or line.startswith("|---"):
            continue
        parts = [p.strip() for p in line.split("|") if p.strip()]
        if not parts or parts[0].lower() in ("produto", "ânion / sal"):
            continue
        if cat is None:
            continue

        nome = parts[0]
        if nome.startswith("(") and "laranja" in nome.lower():
            nome = "Espalhante óleo casca de laranja AD"

        if len(parts) >= 4 and parts[2].lower() not in ("função", "tipo de sal / fonte"):
            # 4 cols: nome, garantias, tipo, origem
            garantias, extra, origem = parts[1], parts[2], parts[3]
            culturas = ""
            conc = f"{garantias} | {extra} ({origem})"
            ia = garantias
        elif len(parts) == 3 and parts[1].lower() in ("garantias",):
            continue
        elif len(parts) == 3:
            col1, col2 = parts[1], parts[2]
            if col1.lower().startswith("garantias") or "observação" in col1.lower():
                continue
            # Heuristic: garantias vs função/dose
            if "%" in col1 or "·" in col1 or "D " in col1 or "P₂O" in col1 or "K₂O" in col1:
                garantias, funcao = col1, col2
                ia = garantias
                culturas = culturas_from_funcao(funcao)
                conc = funcao
            else:
                # função + dose (adjuvantes)
                ia = col1
                conc = col2
                culturas = ""
        elif len(parts) == 2:
            nome, obs = parts[0], parts[1]
            ia = obs
            conc = section
            culturas = "Soja, Feijão"
        else:
            continue

        records.append(
            {
                "nome": nome.replace("'", "\\'"),
                "ia": ia.replace("'", "\\'"),
                "conc": conc.replace("'", "\\'"),
                "cat": cat,
                "unid": unidade(ia, conc),
                "culturas": culturas.replace("'", "\\'"),
                "sec": section.replace("'", "\\'"),
            }
        )
    return records


def main():
    text = MD.read_text(encoding="utf-8")
    records = parse_md(text)
    lines = [
        "// GENERATED by tool/build_nortox_nutricao_catalog.py",
        "",
        "const List<Map<String, String>> catalogNortoxNutricaoRecords = [",
    ]
    for r in records:
        lines.append("  {")
        for k in ("nome", "ia", "conc", "cat", "unid", "culturas", "sec"):
            lines.append(f"    '{k}': r'{r[k]}',")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(records)} products to {OUT}")


if __name__ == "__main__":
    main()
